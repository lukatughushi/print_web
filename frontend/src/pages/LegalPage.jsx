/** /terms and /privacy: the shop's terms and its privacy policy. */
export default function LegalPage({ doc }) {
  const { t, lang } = useI18n();
  const [settings, setSettings] = useState({});
  const page = doc === 'privacy' ? PRIVACY : TERMS;

  useEffect(() => {
    api.get('/api/settings').then((r) => r.data && setSettings(r.data)).catch(() => {});
  }, []);

  const address = settingText(settings, 'contactAddress', lang, t);
  const email = settings.contactEmail || '';
  const phone = settings.contactPhone || '';
  const contacts = (
    <ul className={s.list}>
      {address && <li>{t('მისამართი')}: {address}</li>}
      {email && <li>{t('ელ. ფოსტა')}: <a href={`mailto:${email}`}>{email}</a></li>}
      {phone && <li>{t('ტელეფონი')}: <a href={`tel:${phone.replace(/\s/g, '')}`}>{phone}</a></li>}
    </ul>
  );

  return (
    <div className={s.page}>
      <main className={s.main}>
        <h1 className={s.title}>{page.title}</h1>
        <p className={s.updated}>ბოლო განახლება: {UPDATED}</p>
        {lang !== 'ka' && <p className={s.note}>{t('ეს დოკუმენტი ხელმისაწვდომია მხოლოდ ქართულად.')}</p>}
        <p className={s.lead}>{page.intro}</p>

        {page.sections.map(([heading, parts], i) => (
          <section key={heading} className={s.section}>
            <h2 className={s.h2}>{i + 1}. {heading}</h2>
            {parts.map((part, j) => {
              if (part === '{contacts}') return <div key={j}>{contacts}</div>;
              if (Array.isArray(part)) {
                return <ul key={j} className={s.list}>{part.map((li) => <li key={li}>{li}</li>)}</ul>;
              }
              return <p key={j} className={s.text}>{part}</p>;
            })}
          </section>
        ))}

        <p className={s.other}>
          {doc === 'privacy'
            ? <Link to="/terms">{t('წესები და პირობები')} →</Link>
            : <Link to="/privacy">{t('კონფიდენციალურობის პოლიტიკა')} →</Link>}
        </p>
      </main>
      <SiteFooter settings={settings} />
    </div>
  );
}
